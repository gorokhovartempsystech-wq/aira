"""Authenticated model containers. No disk, network or secret loading on import.

This is a packaging primitive, not a license check or a secure-memory facility.
Callers obtain keys through the separately authenticated licensing service.
"""

import json
import re
import struct
from secrets import token_bytes

MAGIC = b"AIRA-MODEL\x00\x01"
MAX_MODEL_BYTES = 512 * 1024 * 1024
MAX_HEADER_BYTES = 1024
_PREFIX = len(MAGIC) + 4
_ID = re.compile(r"[a-zA-Z0-9][a-zA-Z0-9._-]{0,95}\Z")


class ModelProtectionError(Exception):
    """Never includes keys, source data, paths or crypto exception details."""

    def __init__(self):
        super().__init__("Protected model unavailable or invalid")


def _require(ok):
    if not ok:
        raise ModelProtectionError()


def _identity(model_id, version):
    for value in (model_id, version):
        _require(type(value) is str and _ID.fullmatch(value) is not None)


def _key(key):
    _require(type(key) is bytes and len(key) == 32)


def _json(value):
    return json.dumps(value, sort_keys=True, separators=(",", ":"), ensure_ascii=True).encode()


def seal_model(model, key, *, model_id, version):
    """Encrypt one self-contained ONNX file with a fresh nonce and AES-256-GCM.

    IDs and version are authenticated, public metadata. A release key must be
    randomly generated by trusted release tooling, never derived from a license.
    """
    _key(key)
    _identity(model_id, version)
    _require(type(model) is bytes and 0 < len(model) <= MAX_MODEL_BYTES)
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    header = _json(dict(model_id=model_id, version=version, size=len(model)))
    prefix = MAGIC + struct.pack(">I", len(header)) + header
    nonce = token_bytes(12)
    return prefix + nonce + AESGCM(key).encrypt(nonce, model, prefix)


def open_model(package, key, *, model_id, version):
    """Authenticate the entire container before returning model bytes.

    This function creates no plaintext files. Python/ONNX/OS may retain copies
    in memory, swap or crash dumps: it does not promise memory zeroization.
    Public metadata must match the caller's trusted model selection.
    """
    _key(key)
    _identity(model_id, version)
    _require(type(package) is bytes)
    _require(_PREFIX + 12 + 16 < len(package) <= MAX_MODEL_BYTES + MAX_HEADER_BYTES + 64)
    _require(package[: len(MAGIC)] == MAGIC)
    length = struct.unpack(">I", package[len(MAGIC) : _PREFIX])[0]
    _require(0 < length <= MAX_HEADER_BYTES)
    end = _PREFIX + length
    raw = package[_PREFIX:end]
    try:
        metadata = json.loads(raw)
        _require(type(metadata) is dict and set(metadata) == {"model_id", "version", "size"})
        _require(_json(metadata) == raw)
        _require((metadata["model_id"], metadata["version"]) == (model_id, version))
        size = metadata["size"]
        _require(type(size) is int and 0 < size <= MAX_MODEL_BYTES)
        _require(len(package) == end + 12 + size + 16)
    except (ValueError, TypeError, RecursionError):
        raise ModelProtectionError() from None
    from cryptography.exceptions import InvalidTag
    from cryptography.hazmat.primitives.ciphers.aead import AESGCM

    nonce = package[end : end + 12]
    try:
        return AESGCM(key).decrypt(nonce, package[end + 12 :], package[:end])
    except (InvalidTag, ValueError, OverflowError):
        raise ModelProtectionError() from None
